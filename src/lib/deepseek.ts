- 不要复述课堂原话，也不要把散落的碎片按时间顺序堆出来，要归纳
- 一节课跨多个科目时，按科目分块写，主讲的科目详写，点到为止的科目一句话带过，不要平均分配
- 学生说得含糊、老师没讲清、材料自相矛盾的地方，宁可不写，也不要替他们编一个结论

